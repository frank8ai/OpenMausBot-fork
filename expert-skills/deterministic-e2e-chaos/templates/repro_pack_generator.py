#!/usr/bin/env python3
"""
Deterministic E2E Reproduction Package Generator
Bundles Playwright Trace, HAR, Logs, and System Metadata into a single archive
for offline zero-rework debugging by Fullstack Engineers.
"""
import os
import sys
import zipfile
import json
import datetime

def bundle_repro_pack(test_name: str, results_dir: str = "test-results", output_dir: str = "repro-packs") -> str:
    timestamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    os.makedirs(output_dir, exist_ok=True)
    zip_filename = os.path.join(output_dir, f"repro_{test_name}_{timestamp}.zip")
    
    metadata = {
        "test_name": test_name,
        "timestamp": timestamp,
        "playwright_version": "1.48.0+",
        "browser_engine": "chromium/firefox/webkit",
        "description": "Deterministic reproduction pack generated by Deterministic-E2E-Chaos Skill",
        "artifacts_included": []
    }

    with zipfile.ZipFile(zip_filename, 'w', zipfile.ZIP_DEFLATED) as zf:
        if os.path.exists(results_dir):
            for root, dirs, files in os.walk(results_dir):
                for f in files:
                    if f.endswith(('.zip', '.har', '.png', '.log', '.webm', '.json')):
                        fp = os.path.join(root, f)
                        arcname = os.path.relpath(fp, results_dir)
                        zf.write(fp, arcname=arcname)
                        metadata["artifacts_included"].append(arcname)
        
        # 写入元数据契约文件
        zf.writestr("repro_manifest.json", json.dumps(metadata, indent=2))
        
    print(f"[REPRO-PACK] Successfully built deterministic repro package: {zip_filename}")
    return zip_filename

if __name__ == "__main__":
    test_arg = sys.argv[1] if len(sys.argv) > 1 else "failed_chaos_e2e"
    bundle_repro_pack(test_arg)
